"""LaTeX export of claims as a keyed, self-recording runtime."""

import json
import math
import re
import unicodedata

from claimlink.errors import ClaimExportError

_HEADER = "% AUTO-GENERATED BY CLAIMLINK.\n% DO NOT EDIT MANUALLY.\n"

_SPECIALS = {
    "\\": r"\textbackslash{}",
    "%": r"\%",
    "$": r"\$",
    "&": r"\&",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\mbox{\textasciitilde{}}",
    "^": r"\mbox{\textasciicircum{}}",
    "<": r"\textless{}",
    ">": r"\textgreater{}",
    "|": r"\textbar{}",
}

# The runtime is embedded verbatim in every generated file. It is deliberately
# plain TeX + LaTeX2e: no expl3, no .sty, no hyperref requirement.
_RUNTIME = r"""\makeatletter
% ---- occurrence bookkeeping -----------------------------------------------
\ifdefined\c@claimlinkuses\else\newcounter{claimlinkuses}\fi
% The data stream is opened at the end of this runtime, after the previous
% run's rows are captured for \claimlinkusageself.
% ---- raw accessors: look up a claim without recording a use -----------------
\def\claimlink@rawname#1{\csname clname@#1\endcsname}
\def\claimlink@rawvalue#1{\csname clv@#1\endcsname}
\def\claimlink@rawunit#1{\csname clunit@#1\endcsname}
\def\claimlink@rawdesc#1{\csname cldesc@#1\endcsname}
% \clvalue is expandable and records nothing, for integer/decimal claims with
% siunitx (\num{\clvalue{key}}). Exponent values are \ensuremath{...} and text
% values are formatted LaTeX (not for \edef/\write; use \clv* in headings).
\providecommand{\clvalue}[1]{%
  \claimlink@require{#1}{\clvalue}\csname clv@#1\endcsname}
% ---- unknown keys must fail loudly -----------------------------------------
\def\claimlink@require#1#2{%
  \ifcsname clv@#1\endcsname\else
    \@latex@error{ClaimLink: unknown claim key `#1'}%
      {Key `#1' is not defined in claims.tex; \string#2 needs an exported key.}%
  \fi}
% letter/standalone/minimal have no \thesection.
\def\claimlink@section{\ifdefined\thesection\thesection\else 0\fi}
% ---- record one use: count, target, data line, next-pass table row ----------
% Deferred writes are whatsits: a discarded measurement box drops them; the
% page is fixed at shipout while the section is the one in effect where the
% command is typeset, so floats/saved boxes can pair a source section with a
% shipout page. Do not close at \AtEndDocument, which would run before the
% final page's whatsits and lose its rows.
\def\claimlink@record#1#2{%
  \stepcounter{claimlinkuses}%
  \edef\claimlink@occ{\the\c@claimlinkuses}%
  \@ifpackageloaded{hyperref}{\hypertarget{cl:\claimlink@occ}{}}{}%
  \protected@write\claimlink@datafile{}{#1,#2,\claimlink@occ,\claimlink@section,\thepage}%
  \addcontentsline{clm}{claim}%
    {\protect\clusageentry{#1}{#2}{\claimlink@occ}{\claimlink@section}}%
}
% ---- author-facing API ------------------------------------------------------
% Robust (protected) so \section{...\clv{k}} and \caption{...\clv{k}} can be
% written to .aux/.lof without expanding during \protected@write. The starred
% variants print only the value/unit/description: no occurrence count, anchor,
% .clm row or .clmdata line; use them in section titles and captions. The plain
% forms record again when a TOC or list re-typesets a title.
\protected\def\clv{\@ifstar\claimlink@value@raw\claimlink@value@use}
\protected\def\clunit{\@ifstar\claimlink@unit@raw\claimlink@unit@use}
\protected\def\cldesc{\@ifstar\claimlink@desc@raw\claimlink@desc@use}
\protected\def\clcite#1{%
  \claimlink@require{#1}{\clcite}\claimlink@record{#1}{cite}}
\def\claimlink@value@use#1{%
  \claimlink@require{#1}{\clv}\claimlink@record{#1}{value}\claimlink@rawvalue{#1}}
\def\claimlink@value@raw#1{\claimlink@require{#1}{\clv}\claimlink@rawvalue{#1}}
\def\claimlink@unit@use#1{%
  \claimlink@require{#1}{\clunit}\claimlink@record{#1}{unit}\claimlink@rawunit{#1}}
\def\claimlink@unit@raw#1{\claimlink@require{#1}{\clunit}\claimlink@rawunit{#1}}
\def\claimlink@desc@use#1{%
  \claimlink@require{#1}{\cldesc}\claimlink@record{#1}{description}\claimlink@rawdesc{#1}}
\def\claimlink@desc@raw#1{\claimlink@require{#1}{\cldesc}\claimlink@rawdesc{#1}}
% ---- usage table from the previous pass -------------------------------------
\providecommand{\clusageentry}[4]{%
  \ifdefined\hyperlink
    \hyperlink{cl:#3}{\claimlink@rawname{#1}}%
  \else
    \claimlink@rawname{#1}%
  \fi & #2 & #4}
\providecommand{\l@claim}[2]{%
  #1 & #2\\}
% pdfTeX also searches the output directory, so `pdflatex -output-directory=out`
% finds out/<jobname>.clm and populates the usage table.
% \clusage is meant to be used once per document; a second call sees the
% truncated file.
\def\claimlink@usagehead{%
  \textbf{Claim} & \textbf{Used as} & \textbf{Section} & \textbf{Page}\\}
\def\claimlink@usagefont{%
  \footnotesize
  \setlength{\tabcolsep}{2pt}}
\def\claimlink@usagestart{%
  \begingroup
  % hyperref must not wrap rows in its own link; \clusageentry links the name.
  \@ifpackageloaded{hyperref}{\let\Hy@linktoc\Hy@linktoc@none}{}%
  \claimlink@usagefont}
\def\claimlink@usageopen{%
  \ifdefined\tf@clm\else
    \newwrite\tf@clm
    \immediate\openout\tf@clm=\jobname.clm\relax
  \fi}
\def\claimlink@usagerows{%
  \IfFileExists{\jobname.clm}{\@@input\jobname.clm\relax}{}}
\def\clusage@short{%
  \claimlink@usagestart
  \begin{tabular}{@{}p{0.4\linewidth} p{0.14\linewidth} l l@{}}
    \claimlink@usagehead
    \claimlink@usagerows
  \end{tabular}%
  \claimlink@usageopen
  \endgroup}
% \clusage* needs \usepackage{longtable}; use it for usage lists that span pages, outside floats.
\def\clusage@long{%
  \@ifpackageloaded{longtable}
    {\clusage@longtable}
    {\@latex@error{ClaimLink: \string\clusage* needs \string\usepackage{longtable}}%
      {Load longtable and use \string\clusage* outside a float.}}}
\def\clusage@longtable{%
  \claimlink@usagestart
  \begin{longtable}{@{}p{0.4\linewidth} p{0.14\linewidth} l l@{}}
    \claimlink@usagehead
    \endhead
    \claimlink@usagerows
  \end{longtable}%
  \claimlink@usageopen
  \endgroup}
\providecommand{\clusage}{\@ifstar\clusage@long\clusage@short}
% ---- cross-document usage tables -------------------------------------------
% The main document must be compiled before the supplement; both tables show
% the previous run's rows (the standard second pass).
\ifdefined\claimlink@usageread\else\newread\claimlink@usageread\fi
\ifdefined\claimlink@fieldcount\else\newcount\claimlink@fieldcount\fi
% Print a stored claim name, or the key itself if this lock has no such claim.
% shortcut: an unknown key longer than the claim column can overflow (cross-lock/stale data only).
\def\claimlink@usagekey#1{%
  \ifcsname clname@#1\endcsname\csname clname@#1\endcsname\else\texttt{#1}\fi}
% Self rows link to anchors in this PDF; rows from another PDF stay plain.
\def\claimlink@selfrow#1#2#3#4#5{%
  \ifdefined\hyperlink
    \hyperlink{cl:#3}{\claimlink@usagekey{#1}}%
  \else
    \claimlink@usagekey{#1}%
  \fi & #2 & #4 & #5\\}
\def\claimlink@filerow#1#2#3#4#5{%
  \claimlink@usagekey{#1} & #2 & #4 & #5\\}
% Count fields first: a short line must not scan past its sentinel.
\def\claimlink@countfields#1\@nil{%
  \claimlink@fieldcount=\z@
  \claimlink@countfields@loop#1\@nil}
\def\claimlink@countfields@loop#1,#2\@nil{%
  \advance\claimlink@fieldcount\@ne
  \def\claimlink@next{#2}%
  \ifx\claimlink@next\@empty\else\claimlink@countfields@loop#2\@nil\fi}
% Store rows from a comma-separated .clmdata line; blank lines are skipped.
\def\claimlink@addself#1\relax{%
  \ifx\relax#1\relax\else\claimlink@checkself#1\relax\fi}
\def\claimlink@checkself#1#2\relax{%
  \ifcat\@sptoken#1\else
    \claimlink@countfields#1#2,\@nil
    \ifnum\claimlink@fieldcount=5
      \claimlink@parseself#1#2\relax
    \else
      \@latex@warning{ClaimLink: malformed usage line in \claimlink@usagefile}%
    \fi
  \fi}
\def\claimlink@parseself#1,#2,#3,#4,#5\relax{%
  \expandafter\def\expandafter\claimlink@selfrows\expandafter{%
    \claimlink@selfrows\claimlink@selfrow{#1}{#2}{#3}{#4}{#5}}}
\def\claimlink@addfile#1\relax{%
  \ifx\relax#1\relax\else\claimlink@checkfile#1\relax\fi}
\def\claimlink@checkfile#1#2\relax{%
  \ifcat\@sptoken#1\else
    \claimlink@countfields#1#2,\@nil
    \ifnum\claimlink@fieldcount=5
      \claimlink@parsefile#1#2\relax
    \else
      \@latex@warning{ClaimLink: malformed usage line in \claimlink@usagefile}%
    \fi
  \fi}
\def\claimlink@parsefile#1,#2,#3,#4,#5\relax{%
  \expandafter\def\expandafter\claimlink@filerows\expandafter{%
    \claimlink@filerows\claimlink@filerow{#1}{#2}{#3}{#4}{#5}}}
\def\claimlink@readself{%
  \def\claimlink@usagefile{\jobname.clmdata}%
  \edef\claimlink@endlinechar{\the\endlinechar}%
  \endlinechar=-1
  \openin\claimlink@usageread=\jobname.clmdata\relax
  \claimlink@readselfloop
  \closein\claimlink@usageread
  \endlinechar=\claimlink@endlinechar\relax}
\def\claimlink@readselfloop{%
  \readline\claimlink@usageread to\claimlink@line
  \ifeof\claimlink@usageread
  \else
    \expandafter\claimlink@addself\claimlink@line\relax
    \claimlink@readselfloop
  \fi}
\def\claimlink@readfile#1{%
  \def\claimlink@usagefile{#1}%
  \edef\claimlink@endlinechar{\the\endlinechar}%
  \endlinechar=-1
  \openin\claimlink@usageread=#1\relax
  \claimlink@readfileloop
  \closein\claimlink@usageread
  \endlinechar=\claimlink@endlinechar\relax}
\def\claimlink@readfileloop{%
  \readline\claimlink@usageread to\claimlink@line
  \ifeof\claimlink@usageread
  \else
    \expandafter\claimlink@addfile\claimlink@line\relax
    \claimlink@readfileloop
  \fi}
% A longtable with a repeated header, a wrapping first column and closing rule.
\def\claimlink@usagetable#1{%
  \@ifpackageloaded{longtable}
    {\claimlink@usagetable@do{#1}}
    {\@latex@error{ClaimLink: usage tables need \string\usepackage{longtable}}%
      {Load longtable before \string\claimlinkusagefile\space or \string\claimlinkusageself.}}}
\def\claimlink@usagetable@do#1{%
  \noindent\begin{longtable}{@{}p{0.4\linewidth} p{0.14\linewidth} l l@{}}
    \claimlink@usagehead
    \hline
    \endhead
    #1
    \hline
  \end{longtable}}
% The current document's previous-run rows.
\def\claimlinkusageself{%
  \begingroup
  \claimlink@tablefont
  \claimlink@usagetable{\claimlink@selfrows}%
  \endgroup}
% Rows written by another document's previous run.
\def\claimlinkusagefile#1{%
  \begingroup
  \claimlink@tablefont
  \def\claimlink@filerows{}%
  \IfFileExists{#1.clmdata}{%
    \claimlink@readfile{#1.clmdata}%
    \ifx\claimlink@filerows\empty
      \@latex@warning{ClaimLink: no usage data in #1.clmdata}%
    \fi
  }{%
    \@latex@warning{ClaimLink: no usage data in #1.clmdata}%
  }%
  \claimlink@usagetable{\claimlink@filerows}%
  \endgroup}
% ---- claims table: raw lookups, no recording --------------------------------
% The table merges value and unit into one cell; \clvalue/\clunit stay separate
% for the running text.
\def\claimlink@valueunit#1{%
  \claimlink@rawvalue{#1}%
  \ifcsname clunit@#1\endcsname~\claimlink@rawunit{#1}\fi}
\def\claimlink@tablerow#1#2{%
  \claimlink@rawname{#1} & \claimlink@valueunit{#1} & #2 & \claimlink@rawdesc{#1}\\}
% Rules live inside the multicolumn cell: an \hline between rows shifts the
% first p-column, so the group header would be out of line with its row.
\def\claimlink@tablefile#1{%
  \multicolumn{4}{@{}p{\linewidth}@{}}{%
    \raggedright
    \rule{\linewidth}{0.4pt}\par\nointerlineskip
    \vspace{1pt}%
    \textbf{\textsf{#1}}\par\nointerlineskip
    \vspace{1pt}%
    \rule{\linewidth}{0.4pt}\par}\\*}
\def\claimlink@tablehead{%
  \textbf{Claim} & \textbf{Value} & \textbf{Location} & \textbf{Description}\\}
\def\claimlink@tablefont{%
  \scriptsize
  % Normal row spacing; the 46-claim fixture still fits on the real A4 supplement.
  \renewcommand{\arraystretch}{1.0}
  \setlength{\tabcolsep}{1.5pt}}
% \cltable is a full-width, single-column table. The lower bound is metric-driven:
% each bold header width divided by its column fraction must fit \linewidth.
% It is not intended for twocolumn documents or narrow minipages.
\def\claimlink@tablecols{%
  @{}p{0.34\linewidth}p{0.18\linewidth}p{0.16\linewidth}p{0.27\linewidth}@{}}
\def\claimlink@tablecheck{%
  \begingroup
  \scriptsize
  \settowidth\@tempdima{\textbf{Claim}}%
  \multiply\@tempdima by 100 \divide\@tempdima by 34
  \@tempdimb=\@tempdima
  \settowidth\@tempdima{\textbf{Value}}%
  \multiply\@tempdima by 100 \divide\@tempdima by 18
  \ifdim\@tempdima>\@tempdimb \@tempdimb=\@tempdima \fi
  \settowidth\@tempdima{\textbf{Location}}%
  \multiply\@tempdima by 100 \divide\@tempdima by 16
  \ifdim\@tempdima>\@tempdimb \@tempdimb=\@tempdima \fi
  \settowidth\@tempdima{\textbf{Description}}%
  \multiply\@tempdima by 100 \divide\@tempdima by 27
  \ifdim\@tempdima>\@tempdimb \@tempdimb=\@tempdima \fi
  \ifdim\linewidth<\@tempdimb
    \@latex@warning{ClaimLink: \string\cltable\space needs at least
      \the\@tempdimb\space of line width}%
  \fi
  \endgroup}
\def\cltable@short{%
  \begingroup
  \claimlink@tablecheck
  \claimlink@tablefont
  \expandafter\cltable@short@typeset\expandafter{\claimlink@tablecols}}
% Expand the preamble once: array's \@mkpream does not expand macros.
\def\cltable@short@typeset#1{%
  \noindent\begin{tabular}{#1}
    \claimlink@tablehead
    \cltablerows
    \hline
  \end{tabular}%
  \endgroup}
% \cltable* needs \usepackage{longtable}; use it for tables that span pages, outside floats.
\def\cltable@long{%
  \@ifpackageloaded{longtable}
    {\cltable@longtable}
    {\@latex@error{ClaimLink: \string\cltable* needs \string\usepackage{longtable}}%
      {Load longtable and use \string\cltable* outside a float.}}}
\def\cltable@longtable{%
  \begingroup
  \claimlink@tablecheck
  \claimlink@tablefont
  \expandafter\cltable@longtable@typeset\expandafter{\claimlink@tablecols}}
\def\cltable@longtable@typeset#1{%
  \noindent\begin{longtable}{#1}
    \claimlink@tablehead
    \endhead
    \cltablerows
    \hline
  \end{longtable}%
  \endgroup}
\providecommand{\cltable}{\@ifstar\cltable@long\cltable@short}
% ---- previous-pass capture, then open the write stream ----------------------
% Read \jobname.clmdata before \openout truncates it; re-input keeps the rows.
\ifdefined\claimlink@selfrows\else
  \def\claimlink@selfrows{}%
  \IfFileExists{\jobname.clmdata}{\claimlink@readself}{}%
\fi
\ifdefined\claimlink@datafile\else
  \newwrite\claimlink@datafile
  \immediate\openout\claimlink@datafile=\jobname.clmdata\relax
\fi
"""


def claim_key(name: str) -> str:
    """Return the deterministic key used inside ``\\csname`` lookups."""
    # ß has no NFKD decomposition and would be dropped; expand it like a casefold.
    ascii_name = (
        unicodedata.normalize("NFKD", name.replace("ß", "ss").replace("ẞ", "SS"))
        .encode("ascii", "ignore")
        .decode("ascii")
        .lower()
    )
    key = re.sub(r"[^a-z0-9]+", "-", ascii_name).strip("-")
    if not key:
        raise ClaimExportError(
            f"claim name {name!r} contains no characters usable for a key"
        )
    return key


def escape(text: str) -> str:
    """Escape LaTeX special characters in a single pass."""
    return text.translate(str.maketrans(_SPECIALS))


def format_value(value: object) -> str:
    """Render a JSON-compatible claim value as escaped LaTeX."""
    if isinstance(value, bool):
        return "True" if value else "False"
    if value is None:
        return "None"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise ClaimExportError(f"cannot export non-finite value {value!r}")
        text = repr(value)
        if "e" in text:
            # ``1e-05`` would print literally in the PDF; use real TeX math.
            mantissa, exponent = text.split("e")
            return rf"\ensuremath{{{mantissa} \times 10^{{{int(exponent)}}}}}"
        return text
    if isinstance(value, str):
        return escape(value)
    if isinstance(value, (list, dict)):
        # A hand-edited lock can contain Infinity/NaN, which json.dumps would emit verbatim.
        try:
            dumped = json.dumps(value, ensure_ascii=False, sort_keys=True, allow_nan=False)
        except ValueError:
            raise ClaimExportError(
                f"cannot export value containing a non-finite float: {value!r}"
            ) from None
        return escape(dumped)
    raise ClaimExportError(
        f"cannot export value of unsupported type {type(value).__name__!r}"
    )


def _table_location(claim: dict) -> tuple[str | None, int | None, str | None, str]:
    """Return (file, line, cell_id, source label) for one claim's location."""
    loc = claim.get("location")
    if not isinstance(loc, dict):
        loc = {}
    file = loc.get("file")
    if not isinstance(file, str) or not file:
        file = None
    line = loc.get("line")
    if isinstance(line, bool) or not isinstance(line, int):
        line = None
    cell_id = loc.get("cell_id") if loc.get("type") == "notebook" else None
    if not isinstance(cell_id, str) or not cell_id:
        cell_id = None
    if cell_id is not None:
        source = (
            f"cell {cell_id}" if line is None else f"cell {cell_id}, line {line}"
        )
    elif line is None:
        source = ""
    else:
        source = f"line {line}"
    return file, line, cell_id, source


def _table_rows(claims: list[dict]) -> list[str]:
    """Return the ``\\cltablerows`` body: one file header, then its rows."""
    groups: dict[str | None, list[tuple]] = {}
    for claim in claims:
        file, line, cell_id, source = _table_location(claim)
        entry = (
            line is None,
            line or 0,
            cell_id is None,
            cell_id or "",
            claim_key(claim["name"]),
            source,
        )
        groups.setdefault(file, []).append(entry)

    rows = []
    for file in sorted(groups, key=lambda name: (name is None, name or "")):
        label = "(no location)" if file is None else file
        # shortcut: a single path segment longer than the line still overflows; upgrade if unbroken names can exceed the table width.
        header = escape(label).replace('/', '/\\allowbreak{}')
        rows.append(f"  \\claimlink@tablefile{{{header}}}%")
        for *_, key, source in sorted(groups[file]):
            rows.append(f"  \\claimlink@tablerow{{{key}}}{{{escape(source)}}}%")
    return rows


def generate(registry: dict) -> str:
    """Render the full ``claims.tex`` content for a parsed claim registry."""
    # Must precede the sort, which already reads claim["name"].
    for key, claim in registry["claims"].items():
        if not isinstance(claim.get("name"), str):
            raise ClaimExportError(f"claim {key!r} has no valid name")

    claims = sorted(registry["claims"].values(), key=lambda claim: claim_key(claim["name"]))

    seen: dict[str, str] = {}
    for claim in claims:
        name = claim["name"]
        if "value" not in claim:
            raise ClaimExportError(f"claim {name!r} has no value")
        for field in ("unit", "description"):
            meta = claim.get(field)
            if meta is not None and not isinstance(meta, str):
                raise ClaimExportError(
                    f"claim {name!r} has non-string {field} ({type(meta).__name__})"
                )
        key = claim_key(name)
        if key in seen:
            raise ClaimExportError(
                f"claim names {seen[key]!r} and {name!r} both map to key {key!r}"
            )
        seen[key] = name

    blocks = []
    for claim in claims:
        key = claim_key(claim["name"])
        lines = [
            f"% key: {key}",
            rf"\expandafter\def\csname clname@{key}\endcsname{{{escape(claim['name'])}}}",
            rf"\expandafter\def\csname clv@{key}\endcsname{{{format_value(claim['value'])}}}",
        ]
        if claim.get("unit") is not None:
            lines.append(
                rf"\expandafter\def\csname clunit@{key}\endcsname{{{escape(claim['unit'])}}}"
            )
        if claim.get("description") is not None:
            lines.append(
                rf"\expandafter\def\csname cldesc@{key}\endcsname{{{escape(claim['description'])}}}"
            )
        blocks.append("\n".join(lines))

    out = _HEADER + "\n" + _RUNTIME
    if blocks:
        out += "\n" + "\n\n".join(blocks) + "\n"
    rows = _table_rows(claims)
    if rows:
        out += "\n\\def\\cltablerows{%\n" + "\n".join(rows) + "\n}\n"
    else:
        out += "\n\\def\\cltablerows{}\n"
    out += "\\makeatother\n"
    return out
