@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        ("\\", r"\textbackslash{}"),
        ("%", r"\%"),
        ("$", r"\$"),
        ("&", r"\&"),
        ("#", r"\#"),
        ("_", r"\_"),
        ("{", r"\{"),
        ("}", r"\}"),
        ("~", r"\mbox{\textasciitilde{}}"),
        ("^", r"\mbox{\textasciicircum{}}"),
        ("<", r"\textless{}"),
        (">", r"\textgreater{}"),
        ("|", r"\textbar{}"),
    ],
)
def test_escape_single_characters(raw, expected):
    assert escape(raw) == expected


def test_escape_multiple_and_no_double_escape():
    raw = "50%_of $x$ & #1 {a} ~ ^ \\"
    expected = (
        r"50\%\_of \$x\$ \& \#1 \{a\} \mbox{\textasciitilde{}} "
        r"\mbox{\textasciicircum{}} \textbackslash{}"
    )
    assert escape(raw) == expected
    assert r"\textbackslash\{\}" not in expected
    assert escape("Größe") == "Größe"


@pytest.mark.parametrize(
    ("value", "expected"),
    [
        (124, "124"),
        (4.2, "4.2"),
        (True, "True"),
        (False, "False"),
        (None, "None"),
        ("Dataset % A_b", r"Dataset \% A\_b"),
        ([1, "a&b"], r'[1, "a\&b"]'),
        ({"b": 1, "a": 2}, r'\{"a": 2, "b": 1\}'),
    ],
)
def test_format_value(value, expected):
    assert format_value(value) == expected


def test_format_value_scientific_and_plain_floats():
    assert format_value(0.00001) == r"\ensuremath{1 \times 10^{-5}}"
    assert format_value(1e20) == r"\ensuremath{1 \times 10^{20}}"
    assert format_value(-2.5e-05) == r"\ensuremath{-2.5 \times 10^{-5}}"
    assert format_value(4.2) == "4.2"
    assert format_value(0.0001) == "0.0001"


@pytest.mark.parametrize("value", [float("inf"), float("-inf"), float("nan")])
def test_format_value_rejects_non_finite_floats(value):
    with pytest.raises(ClaimExportError, match="non-finite"):
        format_value(value)


def test_format_value_unsupported_type():
    with pytest.raises(ClaimExportError, match="unsupported"):
        format_value(object())
