"""Tests for :mod:`claimlink.latex`."""

import re

import pytest

from claimlink.errors import ClaimExportError
from claimlink.latex import (
    RESERVED_MACROS,
    escape,
    format_value,
    generate,
    slugify,
)

HEADER = "% AUTO-GENERATED BY CLAIMLINK.\n% DO NOT EDIT MANUALLY.\n"


def claim(name, value, unit=None, description=None):
    return {
        "name": name,
        "value": value,
        "value_type": "int",
        "unit": unit,
        "description": description,
        "location": {"file": "a.py", "line": 1},
        "created_at": "2024-01-01T00:00:00+00:00",
        "updated_at": "2024-01-01T00:00:00+00:00",
    }


def registry(*claims):
    return {"schema_version": 1, "claims": {c["name"]: c for c in claims}}


@pytest.mark.parametrize(
    ("name", "expected"),
    [
        ("number of analyzed papers", "NumberOfAnalyzedPapers"),
        ("accuracy improvement (%)", "AccuracyImprovement"),
        ("top 10 papers", "TopPapers"),
        ("dataset-v2", "DatasetV"),
        ("Größe", "Grosse"),
        ("iPhone", "IPhone"),
        ("2x faster", "XFaster"),
        ("3D reconstruction", "DReconstruction"),
        ("123", ""),
        ("!!!", ""),
        ("  ", ""),
    ],
)
def test_slugify(name, expected):
    assert slugify(name) == expected


@pytest.mark.parametrize(
    "name",
    [
        "number of analyzed papers",
        "accuracy improvement (%)",
        "top 10 papers",
        "dataset-v2",
        "2x faster",
        "3D reconstruction",
        "Größe",
        "123",
        "!!!",
        "  ",
    ],
)
def test_slugify_is_letters_only_ascii(name):
    slug = slugify(name)
    assert slug == "" or (slug.isalpha() and slug.isascii())


@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        ("\\", r"\textbackslash{}"),
        ("%", r"\%"),
        ("$", r"\$"),
        ("&", r"\&"),
        ("#", r"\#"),
        ("_", r"\_"),
        ("{", r"\{"),
        ("}", r"\}"),
        ("~", r"\textasciitilde{}"),
        ("^", r"\textasciicircum{}"),
        ("<", r"\textless{}"),
        (">", r"\textgreater{}"),
        ("|", r"\textbar{}"),
    ],
)
def test_escape_single_characters(raw, expected):
    assert escape(raw) == expected


def test_escape_comparison_and_quote_characters():
    assert format_value('p < 0.05 & 100%') == r"p \textless{} 0.05 \& 100\%"
    assert format_value('say "yes"') == 'say "yes"'


def test_escape_multiple_and_no_double_escape():
    raw = "50%_of $x$ & #1 {a} ~ ^ \\"
    expected = (
        r"50\%\_of \$x\$ \& \#1 \{a\} \textasciitilde{} \textasciicircum{} "
        r"\textbackslash{}"
    )
    assert escape(raw) == expected
    assert r"\textbackslash{}" in expected
    assert r"\textbackslash\{\}" not in expected
    assert escape("Größe") == "Größe"


@pytest.mark.parametrize(
    ("value", "expected"),
    [
        (124, "124"),
        (4.2, "4.2"),
        (True, "True"),
        (False, "False"),
        (None, "None"),
        ("Dataset % A_b", r"Dataset \% A\_b"),
        ([1, "a&b"], r'[1, "a\&b"]'),
        ({"b": 1, "a": 2}, r'\{"a": 2, "b": 1\}'),
    ],
)
def test_format_value(value, expected):
    assert format_value(value) == expected


def test_format_value_unsupported_type():
    with pytest.raises(ClaimExportError, match="unsupported"):
        format_value(object())


def test_generate_exact_output_and_determinism():
    claims = [
        claim("number of analyzed papers", 124, unit="papers"),
        claim(
            "accuracy improvement (%)",
            4.2,
            description="Improvement in accuracy.",
        ),
    ]
    expected = (
        HEADER
        + "\n"
        r"\providecommand{\ClaimValueAccuracyImprovement}{4.2}" "\n"
        r"\providecommand{\ClaimDescriptionAccuracyImprovement}{Improvement in accuracy.}" "\n"
        "\n"
        r"\providecommand{\ClaimValueNumberOfAnalyzedPapers}{124}" "\n"
        r"\providecommand{\ClaimUnitNumberOfAnalyzedPapers}{papers}" "\n"
    )
    assert generate(registry(*claims)) == expected
    reversed_registry = registry(*claims[::-1])
    assert generate(reversed_registry) == expected


def test_generate_optional_macros_only_when_set():
    out = generate(registry(claim("plain", 1)))
    assert r"\ClaimValuePlain}{1}" in out
    assert "ClaimUnit" not in out
    assert "ClaimDescription" not in out

    out = generate(registry(claim("full", 1, unit="u", description="d")))
    assert r"\providecommand{\ClaimUnitFull}{u}" in out
    assert r"\providecommand{\ClaimDescriptionFull}{d}" in out


def test_generate_escapes_value_description_and_unit():
    out = generate(
        registry(claim("percent", "50%_done", unit="% of_a", description="100% sure & #1"))
    )
    assert r"\providecommand{\ClaimValuePercent}{50\%\_done}" in out
    assert r"\providecommand{\ClaimUnitPercent}{\% of\_a}" in out
    assert r"\providecommand{\ClaimDescriptionPercent}{100\% sure \& \#1}" in out


def test_generate_digit_containing_name_is_letters_only():
    out = generate(registry(claim("dataset-v2", 4.2)))
    assert r"\providecommand{\ClaimValueDatasetV}{4.2}" in out
    assert re.search(r"\{\\ClaimValue\d", out) is None


@pytest.mark.parametrize(
    ("record", "match"),
    [
        ({"name": "missing value"}, "no value"),
        (claim("bad unit", 1, unit=42), "unit"),
        (claim("bad description", 1, description=[]), "description"),
        (claim("infinite", float("inf")), "non-finite"),
        (claim("nested nan", [float("nan")]), "non-finite"),
    ],
)
def test_generate_rejects_hand_edited_records(record, match):
    with pytest.raises(ClaimExportError, match=match):
        generate(registry(record))


@pytest.mark.parametrize("record", [{}, {"name": 5, "value": 1}])
def test_generate_rejects_missing_or_non_string_name(record):
    with pytest.raises(ClaimExportError, match=r"'x' has no valid name"):
        generate({"schema_version": 1, "claims": {"x": record}})


def test_generate_collision_names_both_claims():
    with pytest.raises(ClaimExportError) as excinfo:
        generate(registry(claim("number of papers", 1), claim("Number of papers", 2)))
    message = str(excinfo.value)
    assert "number of papers" in message
    assert "Number of papers" in message
    assert "NumberOfPapers" in message


def test_generate_collision_after_dropping_digits():
    with pytest.raises(ClaimExportError) as excinfo:
        generate(registry(claim("dataset v1", 1), claim("dataset v2", 2)))
    message = str(excinfo.value)
    assert "dataset v1" in message
    assert "dataset v2" in message
    assert "DatasetV" in message


def test_generate_reserved_macro_name():
    with pytest.raises(ClaimExportError, match="reserved"):
        generate(registry(claim("claim value", 1)))


@pytest.mark.parametrize("name", ["123", "!!!"])
def test_generate_name_without_letters(name):
    with pytest.raises(ClaimExportError, match="no letters usable"):
        generate(registry(claim(name, 1)))


def test_generate_empty_registry_is_header_only():
    assert generate({"schema_version": 1, "claims": {}}) == HEADER


def test_generate_ends_with_exactly_one_newline():
    out = generate(registry(claim("a", 1), claim("b", 2)))
    assert out.endswith("\n")
    assert not out.endswith("\n\n")


def test_reserved_macros_are_the_documented_set():
    assert RESERVED_MACROS == {"ClaimValue", "ClaimUnit", "ClaimDescription"}
