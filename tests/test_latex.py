"""Tests for :mod:`claimlink.latex`."""

import pytest

from claimlink.errors import ClaimExportError
from claimlink.latex import claim_key, escape, format_value, generate

HEADER = "% AUTO-GENERATED BY CLAIMLINK.\n% DO NOT EDIT MANUALLY.\n"


_DEFAULT_LOCATION = object()


def claim(
    name, value, unit=None, description=None, location=_DEFAULT_LOCATION
):
    if location is _DEFAULT_LOCATION:
        location = {"file": "a.py", "line": 1}
    return {
        "name": name,
        "value": value,
        "value_type": "int",
        "unit": unit,
        "description": description,
        "location": location,
        "created_at": "2024-01-01T00:00:00+00:00",
        "updated_at": "2024-01-01T00:00:00+00:00",
    }


def registry(*claims):
    return {"schema_version": 1, "claims": {c["name"]: c for c in claims}}


@pytest.mark.parametrize(
    ("name", "expected"),
    [
        ("number of analyzed papers", "number-of-analyzed-papers"),
        ("articles in 2022", "articles-in-2022"),
        ("V1 variables", "v1-variables"),
        ("V2 variables", "v2-variables"),
        ("accuracy improvement (%)", "accuracy-improvement"),
        ("Größe", "grosse"),
        ("ẞ", "ss"),
        ("2x faster", "2x-faster"),
        ("Papers", "papers"),
        ("  spaces -- and!! punctuation  ", "spaces-and-punctuation"),
    ],
)
def test_claim_key(name, expected):
    assert claim_key(name) == expected


@pytest.mark.parametrize("name", ["!!!", "  ", "%"])
def test_claim_key_rejects_names_without_usable_characters(name):
    with pytest.raises(ClaimExportError, match="no characters usable"):
        claim_key(name)


def test_generate_starts_with_header_and_contains_runtime():
    out = generate(registry(claim("alpha", 1)))
    assert out.startswith(HEADER + "\n")
    for marker in (
        r"\protected\def\clv",
        r"\protected\def\clunit",
        r"\protected\def\cldesc",
        r"\protected\def\clcite",
        r"\providecommand{\cltable}",
        r"\providecommand{\clusage}",
        r"\def\claimlink@record",
        r"\immediate\openout\claimlink@datafile=\jobname.clmdata",
        r"\makeatother",
    ):
        assert marker in out


def test_generate_uses_namespaced_private_macros():
    out = generate(registry(claim("alpha", 1)))
    assert "\\cl@" not in out
    assert r"\def\claimlink@record" in out


def test_table_file_header_is_fenced_bold_and_coupled():
    out = generate(registry(claim("alpha", 1)))
    assert (
        "\\def\\claimlink@tablefile#1{%\n"
        "  \\multicolumn{4}{@{}p{\\linewidth}@{}}{%\n"
        "    \\raggedright\n"
        "    \\rule{\\linewidth}{0.4pt}\\par\\nointerlineskip\n"
        "    \\vspace{1pt}%\n"
        "    \\textbf{\\textsf{#1}}\\par\\nointerlineskip\n"
        "    \\vspace{1pt}%\n"
        "    \\rule{\\linewidth}{0.4pt}\\par}\\\\*}"
    ) in out


def test_runtime_exposes_cross_document_usage_tables():
    out = generate(registry(claim("alpha", 1)))
    for marker in (
        r"\def\claimlinkusagefile#1",
        r"\def\claimlinkusageself",
        r"\readline\claimlink@usageread",
        r"\endlinechar=-1",
        r"\ifx\claimlink@filerows\empty",
        r"\@latex@warning{ClaimLink: no usage data in #1.clmdata}",
    ):
        assert marker in out
    # Rows are captured before the deferred write stream truncates the file.
    assert out.index(r"\IfFileExists{\jobname.clmdata}") < out.index(
        r"\immediate\openout\claimlink@datafile"
    )


def test_runtime_counts_usage_fields_before_parsing():
    out = generate(registry(claim("alpha", 1)))
    assert (
        r"\ifdefined\claimlink@fieldcount\else"
        r"\newcount\claimlink@fieldcount\fi"
    ) in out
    assert r"\def\claimlink@countfields#1\@nil" in out
    assert out.count(r"\ifnum\claimlink@fieldcount=5") == 2
    assert out.count(
        r"\@latex@warning{ClaimLink: malformed usage line in \claimlink@usagefile}"
    ) == 2
    assert r"\def\claimlink@usagefile{\jobname.clmdata}" in out
    # Short \clusage, long \clusage*, and the cross-document tables share it.
    assert out.count(
        r"@{}p{0.4\linewidth} p{0.14\linewidth} l l@{}"
    ) == 3


def test_claim_tables_have_a_closing_rule():
    out = generate(registry(claim("alpha", 1)))
    assert (
        "    \\claimlink@tablehead\n"
        "    \\cltablerows\n"
        "    \\hline\n"
        "  \\end{tabular}%"
    ) in out
    assert (
        "    \\endhead\n"
        "    \\cltablerows\n"
        "    \\hline\n"
        "  \\end{longtable}%"
    ) in out


def test_generate_sorts_data_by_key_and_sets_tablerows():
    out = generate(registry(claim("zeta", 1), claim("Alpha", 2)))
    assert out.index("% key: alpha") < out.index("% key: zeta")
    assert out.endswith(
        "\\def\\cltablerows{%\n"
        "  \\claimlink@tablefile{a.py}%\n"
        "  \\claimlink@tablerow{alpha}{line 1}%\n"
        "  \\claimlink@tablerow{zeta}{line 1}%\n"
        "}\n"
        "\\makeatother\n"
    )


def test_generate_groups_table_rows_by_file_and_formats_provenance():
    out = generate(
        registry(
            claim(
                "papers",
                124,
                unit="papers",
                description="100% & #1",
                location={"type": "script", "file": "analysis/run_50%.py", "line": 5},
            ),
            claim(
                "long path claim",
                7,
                location={
                    "type": "script",
                    "file": "experiments/very/long/directory/structure/analysis_pipeline.py",
                    "line": 10,
                },
            ),
            claim(
                "beta notebook",
                2,
                location={
                    "type": "notebook",
                    "file": "notebooks/report.ipynb",
                    "cell_id": "cell-b",
                    "line": 32,
                },
            ),
            claim(
                "alpha notebook",
                1,
                location={
                    "type": "notebook",
                    "file": "notebooks/report.ipynb",
                    "cell_id": "cell_1%",
                    "line": 32,
                },
            ),
            claim("unknown place", 1, location=None),
        )
    )
    assert out.endswith(
        "\\def\\cltablerows{%\n"
        "  \\claimlink@tablefile{analysis/\\allowbreak{}run\\_50\\%.py}%\n"
        "  \\claimlink@tablerow{papers}{line 5}%\n"
        "  \\claimlink@tablefile{experiments/\\allowbreak{}very/\\allowbreak{}"
        "long/\\allowbreak{}directory/\\allowbreak{}structure/\\allowbreak{}"
        "analysis\\_pipeline.py}%\n"
        "  \\claimlink@tablerow{long-path-claim}{line 10}%\n"
        "  \\claimlink@tablefile{notebooks/\\allowbreak{}report.ipynb}%\n"
        "  \\claimlink@tablerow{beta-notebook}{cell cell-b, line 32}%\n"
        "  \\claimlink@tablerow{alpha-notebook}{cell cell\\_1\\%, line 32}%\n"
        "  \\claimlink@tablefile{(no location)}%\n"
        "  \\claimlink@tablerow{unknown-place}{}%\n"
        "}\n"
        "\\makeatother\n"
    )
    assert out.count("\\claimlink@tablefile{") == 4
    # Unit and description stay separate in the data block; the table merges
    # value and unit at typeset time.
    assert r"\csname clunit@papers\endcsname{papers}" in out
    assert r"\csname cldesc@papers\endcsname{100\% \& \#1}" in out
    assert "clunit@alpha-notebook" not in out


def test_generate_uses_no_location_label_for_missing_or_empty_file():
    out = generate(
        registry(
            claim("real unknown", 1, location={"file": "unknown", "line": 1}),
            claim("missing", 2, location=None),
            claim("blank", 3, location={"file": "", "line": 2}),
        )
    )
    assert out.endswith(
        "\\def\\cltablerows{%\n"
        "  \\claimlink@tablefile{unknown}%\n"
        "  \\claimlink@tablerow{real-unknown}{line 1}%\n"
        "  \\claimlink@tablefile{(no location)}%\n"
        "  \\claimlink@tablerow{blank}{line 2}%\n"
        "  \\claimlink@tablerow{missing}{}%\n"
        "}\n"
        "\\makeatother\n"
    )
    assert out.count("\\claimlink@tablefile{(no location)}") == 1


def test_generate_notebook_source_keeps_cell_id_without_line():
    out = generate(
        registry(
            claim(
                "cell only",
                1,
                location={"type": "notebook", "file": "n.ipynb", "cell_id": "13"},
            )
        )
    )
    assert r"\claimlink@tablerow{cell-only}{cell 13}%" in out


def test_generate_exact_data_block():
    out = generate(
        registry(claim("Articles in 2022", 43, unit="articles", description="Count."))
    )
    block = (
        "% key: articles-in-2022\n"
        r"\expandafter\def\csname clname@articles-in-2022\endcsname{Articles in 2022}" "\n"
        r"\expandafter\def\csname clv@articles-in-2022\endcsname{43}" "\n"
        r"\expandafter\def\csname clunit@articles-in-2022\endcsname{articles}" "\n"
        r"\expandafter\def\csname cldesc@articles-in-2022\endcsname{Count.}" "\n"
    )
    assert block in out


def test_generate_omits_absent_optional_fields():
    out = generate(registry(claim("plain", 1)))
    assert r"\csname clv@plain\endcsname{1}" in out
    assert "clunit@plain" not in out
    assert "cldesc@plain" not in out


def test_generate_empty_registry_is_header_runtime_and_empty_tablerows():
    out = generate({"schema_version": 1, "claims": {}})
    assert out.startswith(HEADER + "\n")
    assert "% key:" not in out
    assert out.endswith("\\def\\cltablerows{}\n\\makeatother\n")


def test_generate_is_deterministic_regardless_of_insertion_order():
    claims = [claim("b", 2), claim("a", 1)]
    assert generate(registry(*claims)) == generate(registry(*claims[::-1]))


def test_generate_escapes_names_units_descriptions_and_values():
    out = generate(
        registry(
            claim(
                "50% & more",
                "50%_done",
                unit="% of_a",
                description="100% sure & #1",
            )
        )
    )
    assert r"\csname clname@50-more\endcsname{50\% \& more}" in out
    assert r"\csname clv@50-more\endcsname{50\%\_done}" in out
    assert r"\csname clunit@50-more\endcsname{\% of\_a}" in out
    assert r"\csname cldesc@50-more\endcsname{100\% sure \& \#1}" in out


@pytest.mark.parametrize(
    ("value", "expected"),
    [
        (0.00001, r"\ensuremath{1 \times 10^{-5}}"),
        (1e20, r"\ensuremath{1 \times 10^{20}}"),
        (-2.5e-05, r"\ensuremath{-2.5 \times 10^{-5}}"),
        (4.2, "4.2"),
        (0.0001, "0.0001"),
    ],
)
def test_generate_scientific_floats(value, expected):
    out = generate(registry(claim("tiny", value)))
    assert rf"\csname clv@tiny\endcsname{{{expected}}}" in out


def test_generate_keeps_numeric_keys_distinct():
    out = generate(
        registry(claim("articles in 2022", 1), claim("articles in 2023", 2))
    )
    assert "% key: articles-in-2022" in out
    assert "% key: articles-in-2023" in out


def test_generate_collision_names_both_claims_and_the_key():
    with pytest.raises(ClaimExportError) as excinfo:
        generate(registry(claim("Papers", 1), claim("papers", 2)))
    message = str(excinfo.value)
    assert "Papers" in message
    assert "papers" in message
    assert "'papers'" in message


