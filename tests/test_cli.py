def test_export_refuses_to_overwrite_input_via_symlink(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    before = write_lock(tmp_path / "claim-lock.json", CLAIMS)
    (tmp_path / "link.tex").symlink_to(tmp_path / "claim-lock.json")

    assert main(["export", "--output", "link.tex"]) == 1

    assert "refusing" in capsys.readouterr().err
    assert (tmp_path / "claim-lock.json").read_bytes() == before


def test_export_refuses_to_overwrite_input_via_traversal(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    before = write_lock(tmp_path / "claim-lock.json", CLAIMS)
    assert not (tmp_path / "sub").exists()

    assert main(["export", "--output", "./sub/../claim-lock.json"]) == 1

    assert "refusing" in capsys.readouterr().err
    assert (tmp_path / "claim-lock.json").read_bytes() == before


