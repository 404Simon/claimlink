"""Tests for the ``claimlink export`` command."""

import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

from claimlink import latex, storage
from claimlink.cli import main

CLAIMS = {
    "number of papers": {
        "name": "number of papers",
        "value": 42,
        "unit": "papers",
    }
}


def write_lock(path: Path, claims: dict) -> bytes:
    data = json.dumps({"schema_version": 1, "claims": claims}).encode("utf-8")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return data


def test_export_defaults(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    input_path = tmp_path / "claim-lock.json"
    write_lock(input_path, CLAIMS)

    assert main(["export"]) == 0

    data = (tmp_path / "claims.tex").read_bytes()
    text = data.decode("utf-8")
    assert text.startswith("% AUTO-GENERATED BY CLAIMLINK.")
    assert r"\providecommand" in text
    assert data == latex.generate(storage.load(input_path)).encode("utf-8")
    assert b"\r" not in data
    assert f"Wrote {Path('claims.tex')}" in capsys.readouterr().out


def test_export_defaults_to_claimlink_root(tmp_path, monkeypatch):
    project = tmp_path / "project"
    other = tmp_path / "elsewhere"
    other.mkdir()
    write_lock(project / "claim-lock.json", CLAIMS)
    monkeypatch.setenv("CLAIMLINK_ROOT", str(project))
    monkeypatch.chdir(other)

    assert main(["export"]) == 0

    data = (other / "claims.tex").read_bytes()
    expected = latex.generate(storage.load(project / "claim-lock.json"))
    assert data == expected.encode("utf-8")


def test_export_unencodable_unit_leaves_output_untouched(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    claims = {"bad": {"name": "bad", "value": 1, "unit": "\ud800"}}
    write_lock(tmp_path / "claim-lock.json", claims)
    output = tmp_path / "claims.tex"
    output.write_bytes(b"OLD")

    assert main(["export"]) == 1

    err = capsys.readouterr().err
    assert "claimlink: error:" in err
    assert "Traceback" not in err
    assert output.read_bytes() == b"OLD"


def test_export_custom_paths_creates_directories(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    write_lock(tmp_path / "data" / "lock.json", CLAIMS)
    output = tmp_path / "build" / "nested" / "claims.tex"

    assert main(["export", "--input", "data/lock.json", "--output", str(output)]) == 0

    assert output.is_file()
    assert str(output) in capsys.readouterr().out


def test_export_missing_input(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)

    assert main(["export"]) == 1

    err = capsys.readouterr().err
    assert err.startswith("claimlink: error:")
    assert "file not found" in err
    assert "claim-lock.json" in err
    assert not (tmp_path / "claims.tex").exists()


def test_export_malformed_json(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    (tmp_path / "claim-lock.json").write_text("{not json", encoding="utf-8")

    assert main(["export"]) == 1

    assert "claim-lock.json" in capsys.readouterr().err
    assert not (tmp_path / "claims.tex").exists()


def test_export_duplicate_macro_collision(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    claims = {
        "model accuracy": {"name": "model accuracy", "value": 1},
        "model-accuracy": {"name": "model-accuracy", "value": 2},
    }
    write_lock(tmp_path / "claim-lock.json", claims)

    assert main(["export"]) == 1

    err = capsys.readouterr().err
    assert "ModelAccuracy" in err
    assert not (tmp_path / "claims.tex").exists()


def test_export_overwrites_existing_output(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    write_lock(tmp_path / "claim-lock.json", CLAIMS)
    output = tmp_path / "claims.tex"
    output.write_text("OLD CONTENT\n", encoding="utf-8")

    assert main(["export"]) == 0

    text = output.read_text(encoding="utf-8")
    assert "OLD CONTENT" not in text
    assert text.startswith("% AUTO-GENERATED BY CLAIMLINK.")


def test_export_leaves_input_bytes_unchanged(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    before = write_lock(tmp_path / "claim-lock.json", CLAIMS)

    assert main(["export"]) == 0

    assert (tmp_path / "claim-lock.json").read_bytes() == before


def test_no_subcommand_exits_with_usage_error():
    with pytest.raises(SystemExit) as excinfo:
        main([])
    assert excinfo.value.code == 2


