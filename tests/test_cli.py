def test_export_via_console_script(tmp_path):
    script = str(Path(sys.executable).with_name("claimlink"))
    if not Path(script).is_file():
        pytest.skip("claimlink console script not installed")

    good = tmp_path / "good"
    good.mkdir()
    write_lock(good / "claim-lock.json", CLAIMS)
    result = subprocess.run(
        [script, "export"], cwd=good, capture_output=True, text=True
    )
    assert result.returncode == 0
    assert (good / "claims.tex").is_file()

    missing = tmp_path / "missing"
    missing.mkdir()
    result = subprocess.run(
        [script, "export"], cwd=missing, capture_output=True, text=True
    )
    assert result.returncode == 1
    assert "claimlink: error:" in result.stderr
    assert "Traceback" not in result.stderr


@pytest.mark.skipif(sys.platform == "win32", reason="POSIX pipe semantics")
def test_export_survives_closed_pipe(tmp_path):
    script = str(Path(sys.executable).with_name("claimlink"))
    if not Path(script).is_file():
        pytest.skip("claimlink console script not installed")
    write_lock(tmp_path / "claim-lock.json", CLAIMS)

    read_fd, write_fd = os.pipe()
    os.close(read_fd)
    result = subprocess.run(
        [script, "export"],
        cwd=tmp_path,
        stdout=write_fd,
        stderr=subprocess.PIPE,
        text=True,
    )
    os.close(write_fd)

    assert result.returncode == 0
    assert result.stderr == ""
    assert (tmp_path / "claims.tex").is_file()
