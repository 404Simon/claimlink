def test_export_refuses_to_overwrite_input(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    before = write_lock(tmp_path / "claim-lock.json", CLAIMS)

    assert main(["export", "--output", "claim-lock.json"]) == 1

    err = capsys.readouterr().err
